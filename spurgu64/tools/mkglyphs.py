def main(out):
    lines = ["/* generated by tools/mkglyphs.py -- custom glyphs for screen codes",
             "   $80.. of the RAM character set */",
             "#define GLYPH_FIRST 0x80",
             "#define GLYPH_COUNT %d" % len(GLYPHS),
             "static const unsigned char Glyphs[GLYPH_COUNT * 8] = {"]
    for name, art in GLYPHS:
        rows = [r for r in art.strip().split("\n")]
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
        b = [int(r.replace(".", "0").replace("#", "1"), 2) for r in rows]
        lines.append("  " + ",".join("0x%02X" % v for v in b) + ",  /* %s */" % name)
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "glyphs.h")
