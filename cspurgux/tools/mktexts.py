#!/usr/bin/env python3
"""Embeds the original SpurguX text files in a C header.

    mktexts.py DIR OUT.h        (DIR holds SPU.HLP, SPU.SPE and SPU.TIP)

For each file the header defines a macro with the file's lines as C89
string literals, one per line, ready for an array initializer:

    #define SPU_HLP_LINES "line 1", "line 2", ...

The lines are exactly what the old file reader returned: CR LF, CR or LF
end a line, ^Z ends the file, tabs become spaces, other control
characters are dropped and a line is cut at 80 characters.  The text stays
CP437; bytes above 127 are written as octal escapes.  Each literal is at
most 80 characters, well under C89's 509-character limit.

The generated spudata.h is kept in the repository, so the game builds and
runs without the original files; this script is only needed to regenerate
it (`make texts`)."""
import sys

FILES = (("SPU.HLP", "SPU_HLP_LINES"),
         ("SPU.SPE", "SPU_SPE_LINES"),
         ("SPU.TIP", "SPU_TIP_LINES"))
SCRW = 80


def lines_of(data):
    """the lines TextLine() returned for this file"""
    out, line, got, i = [], bytearray(), False, 0
    while True:
        if i >= len(data) or data[i] == 26:
            if got:
                out.append(bytes(line))
            return out
        c = data[i]
        i += 1
        got = True
        if c in (13, 10):
            if c == 13 and i < len(data) and data[i] == 10:
                i += 1
            out.append(bytes(line))
            line, got = bytearray(), False
            continue
        if c == 9:
            c = 32
        if c >= 32 and len(line) < SCRW:
            line.append(c)


def literal(b):
    s = '"'
    for c in b:
        if c in (0x22, 0x5C, 0x3F):      # " \ and ? (no trigraphs)
            s += "\\" + chr(c)
        elif 32 <= c < 127:
            s += chr(c)
        else:
            s += "\\%03o" % c
    return s + '"'


def main():
    src, dst = sys.argv[1:3]
    out = ["/* spudata.h -- the original SpurguX v1.17 text files, (C) 1987",
           "   Petri Niska, as CP437 string literals one line each.",
           "   Generated by tools/mktexts.py from SPU.HLP, SPU.SPE and SPU.TIP. */",
           "#ifndef SPUDATA_H", "#define SPUDATA_H"]
    for name, macro in FILES:
        lines = lines_of(open("%s/%s" % (src, name), "rb").read())
        out.append("")
        out.append("/* %s: %d lines */" % (name, len(lines)))
        out.append("#define %s \\" % macro)
        for k, ln in enumerate(lines):
            out.append("  " + literal(ln) + (", \\" if k + 1 < len(lines) else ""))
    out += ["", "#endif"]
    open(dst, "w", encoding="ascii").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
